THIN = Side(style="thin", color="999999")
BOX = Border(left=THIN, right=THIN, top=THIN, bottom=THIN)
HEAD = PatternFill("solid", fgColor="E7E7E7")
FILL = {OK: "E8F5E9", COND: "FFF4D6", NO: "FDE2E2"}


def write_sheet(ws, headers, rows, widths, judge_cols=()):
    ws.append(headers)
    for c in ws[1]:
        c.font = Font(name="맑은 고딕", bold=True)
        c.fill = HEAD
        c.border = BOX
        c.alignment = Alignment(horizontal="center", vertical="center", wrap_text=True)
    for r in rows:
        ws.append(list(r))
    for row in ws.iter_rows(min_row=2):
        for c in row:
            c.font = Font(name="맑은 고딕")
            c.border = BOX
            c.alignment = Alignment(vertical="top", wrap_text=True)
            if c.column in judge_cols and c.value in FILL:
                c.fill = PatternFill("solid", fgColor=FILL[c.value])
    for i, w in enumerate(widths, start=1):
        ws.column_dimensions[ws.cell(1, i).column_letter].width = w
    ws.freeze_panes = "B2"


