def count_flags():
    """처음 판정이 조건부 또는 (처음부터) 비교 불가인 조건·항목 줄 수 (합계·'대상 아님' 표시 줄 제외)."""
    out = {}
    for no, rows in ROWS.items():
        n = 0
        for row in rows:
            name, first = row[0], row[3]
            if name.startswith("합계") or name.startswith("해상운임 (20"):
                continue
            if first in (COND, NO):
                n += 1
        out[no] = n
    return out


